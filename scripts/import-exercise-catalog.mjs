import { access, cp, mkdir, readFile, rm, writeFile } from "node:fs/promises"
import path from "node:path"
import process from "node:process"

const FREE_EXERCISE_DB_COMMIT = "b0eed061e1c832b3ed815fbaa4b45b3cdc14df49"
const LIBREFIT_COMMIT = "cb465ef99f9c680df4a296c24f1ba460ab54cfba"

const LEGACY_EXERCISES = {
  "Barbell_Bench_Press_-_Medium_Grip": { id: "bench-press", name: "Bench Press" },
  "Barbell_Full_Squat": { id: "squat", name: "Squat" },
  "Barbell_Deadlift": { id: "deadlift", name: "Deadlift" },
  "Standing_Military_Press": { id: "overhead-press", name: "Overhead Press" },
  "Pullups": { id: "pull-up", name: "Pull Up" },
  "Plank": { id: "plank", name: "Plank" },
  "Running_Treadmill": { id: "running", name: "Running" },
}

const projectRoot = path.resolve(import.meta.dirname, "..")
const freeExerciseDbRoot = path.resolve(process.argv[2] ?? "")
const libreFitRoot = path.resolve(process.argv[3] ?? "")

function normalizeLabel(value) {
  return value
    .trim()
    .split(/\s+/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1).toLowerCase())
    .join(" ")
}

function getTrackingCategory(exercise) {
  if (exercise.category === "cardio") return "CARDIO"
  if (exercise.category === "stretching" || exercise.force === "static") return "TIMED"
  if (exercise.equipment === "body only") return "BODYWEIGHT"
  return "STRENGTH"
}

function getAppIdentity(exercise) {
  return LEGACY_EXERCISES[exercise.id] ?? { id: exercise.id, name: exercise.name }
}

async function hasExerciseImages(exercise) {
  const sourceRoot = path.join(libreFitRoot, "app/src/main/assets", exercise.id)
  try {
    await access(path.join(sourceRoot, "0.webp"))
    await access(path.join(sourceRoot, "1.webp"))
    return true
  } catch {
    return false
  }
}

function buildCatalogExercise(exercise, hasImages) {
  const identity = getAppIdentity(exercise)
  const primaryMuscles = exercise.primaryMuscles.map(normalizeLabel)
  const secondaryMuscles = exercise.secondaryMuscles.map(normalizeLabel)

  return {
    id: identity.id,
    sourceId: exercise.id,
    name: identity.name,
    category: getTrackingCategory(exercise),
    sourceCategory: normalizeLabel(exercise.category),
    muscleGroups: [...new Set([...primaryMuscles, ...secondaryMuscles])],
    primaryMuscles,
    secondaryMuscles,
    equipment: exercise.equipment ? normalizeLabel(exercise.equipment) : "Other",
    level: exercise.level ? normalizeLabel(exercise.level) : "Unknown",
    force: exercise.force ? normalizeLabel(exercise.force) : undefined,
    mechanic: exercise.mechanic ? normalizeLabel(exercise.mechanic) : undefined,
    instructionSteps: exercise.instructions.map((step) => step.trim()).filter(Boolean),
    hasImages,
  }
}

async function copyExerciseImages(exercise, destinationRoot) {
  const identity = getAppIdentity(exercise)
  const sourceRoot = path.join(libreFitRoot, "app/src/main/assets", exercise.id)
  const destination = path.join(destinationRoot, identity.id)

  await mkdir(destination, { recursive: true })
  await cp(path.join(sourceRoot, "0.webp"), path.join(destination, "start.webp"))
  await cp(path.join(sourceRoot, "1.webp"), path.join(destination, "finish.webp"))
}

function buildImageManifest(exerciseIds) {
  const cases = exerciseIds.map(
    (id) => `    case ${JSON.stringify(id)}:
      return [
        require("../../assets/exercises/${id}/start.webp"),
        require("../../assets/exercises/${id}/finish.webp"),
      ]`,
  )

  return [
    "/* This file is generated by scripts/import-exercise-catalog.mjs. */",
    "",
    "export type ExerciseImagePair = readonly [number, number]",
    "",
    "export const EXERCISE_IMAGE_IDS = [",
    ...exerciseIds.map((id) => `  ${JSON.stringify(id)},`),
    "] as const",
    "",
    "export function getGeneratedExerciseImages(",
    "  exerciseId: string,",
    "): ExerciseImagePair | undefined {",
    "  switch (exerciseId) {",
    ...cases,
    "    default:",
    "      return undefined",
    "  }",
    "}",
    "",
  ].join("\n")
}

async function loadSourceExercises() {
  if (!process.argv[2] || !process.argv[3]) {
    throw new Error("Usage: bun scripts/import-exercise-catalog.mjs <free-exercise-db> <LibreFit>")
  }

  const source = await readFile(path.join(freeExerciseDbRoot, "dist/exercises.json"), "utf8")
  const exercises = JSON.parse(source)
  if (!Array.isArray(exercises) || exercises.length !== 873) {
    throw new Error(`Expected 873 source exercises, received ${exercises.length}`)
  }
  return exercises
}

async function main() {
  const exercises = await loadSourceExercises()
  const imageAvailability = await Promise.all(exercises.map(hasExerciseImages))
  const catalog = exercises.map((exercise, index) =>
    buildCatalogExercise(exercise, imageAvailability[index]),
  )
  const exercisesWithImages = exercises.filter((_, index) => imageAvailability[index])
  const assetRoot = path.join(projectRoot, "assets/exercises")
  const dataRoot = path.join(projectRoot, "app/data")

  await rm(assetRoot, { recursive: true, force: true })
  await mkdir(assetRoot, { recursive: true })
  await mkdir(dataRoot, { recursive: true })

  for (const exercise of exercisesWithImages) await copyExerciseImages(exercise, assetRoot)

  await writeFile(
    path.join(dataRoot, "exerciseCatalog.generated.json"),
    `${JSON.stringify(catalog)}\n`,
  )
  await writeFile(
    path.join(dataRoot, "exerciseImages.generated.ts"),
    buildImageManifest(exercisesWithImages.map((exercise) => getAppIdentity(exercise).id)),
  )

  const report = {
    exerciseCount: catalog.length,
    imageCount: exercisesWithImages.length * 2,
    missingImageExerciseIds: catalog.filter((exercise) => !exercise.hasImages).map(({ id }) => id),
    freeExerciseDbCommit: FREE_EXERCISE_DB_COMMIT,
    libreFitCommit: LIBREFIT_COMMIT,
  }
  await writeFile(
    path.join(dataRoot, "exerciseCatalog.report.json"),
    `${JSON.stringify(report, null, 2)}\n`,
  )
}

await main()
